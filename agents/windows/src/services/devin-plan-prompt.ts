/**
 * #368 Phase 2a: Devin プランモードの根治のための前置きプロンプト生成。
 *
 * #363〜#368 で確定した真因: Devin の `Exec()` パーミッションはトークン単位のプレフィックス一致で
 * あり、複合シェルコマンド（`&&`/`;`/パイプ）を個々の裸コマンド名に分解して判定するため、
 * allow-list 方式は構造的にモグラ叩きになる。並列ツール呼び出しのうち1つでも拒否されると
 * ターン全体が "Interrupting stop token" でキャンセルされ、exit 0・出力ゼロの無言終了になる。
 *
 * Phase 2a はこの構造的欠陥を「パーミッションで縛る」のではなく「常に `--permission-mode dangerous`
 * で実行し、自然言語の前置きプロンプトで規律を保たせ、安全性は git 自動復元ガード
 * （`git-guard.ts`）で担保する」方式に転換する。本モジュールはその前置き文字列を生成する。
 *
 * `devin-file-watch.ts`/`devin-atif.ts`/`git-guard-core.ts` と同じ流儀
 * （外部 import ゼロ、3 OS byte-for-byte 同一）。
 */

/**
 * Devin のプランモードターンに前置きするプロンプト文字列を組み立てる。
 *
 * 4点の規律を明示する:
 * 1. このターンは調査と説明に徹し、実装（ファイルの書き込み）は `exec` 指示を受けてから行うこと
 * 2. 書き込み系コマンド（ファイル作成・編集・削除、`git commit`/`git push` 等）を使わないこと
 * 3. 複合コマンド（`&&`/`;`/パイプ）は自由に使ってよいこと（#368 Phase 1 で確定した真因への対策——
 *    Devin 自身に「複合コマンドを避けろ」と指示する必要は無く、むしろ積極的に使わせることで
 *    トークン単位のパーミッション判定という構造的欠陥を回避する）
 * 4. 勝手にプランモードを抜けない（ユーザーが `e`/`exec` を送るまで待つ）こと
 *
 * 万一この規律に反してファイルが書き換わっても、ターン終了後に git 自動復元ガードが
 * 元の状態へ戻すことも明記し、Devin が過度に萎縮せず調査に必要な操作を行えるようにする。
 */
export function buildDevinPlanPreamble(): string {
  return [
    '【プランモードの規律】',
    '1. このターンは調査と説明に徹してください。ファイルの作成・編集・削除などの実装は、ユーザーが `exec` を送信した後に行ってください。',
    '2. 書き込み系のコマンド（ファイルの作成・編集・削除、`git commit`・`git push`・`git add` 等）は使わないでください。',
    '3. 複合コマンド（`&&`・`;`・パイプでの連結）は自由に使って構いません。',
    '4. ユーザーが `e` または `exec` を送信するまで、勝手にプランモードを抜けないでください。',
    '（万一このターン中に誤ってファイルが変更された場合でも、ターン終了後に自動で元の状態へ復元されます。）',
  ].join('\n');
}
