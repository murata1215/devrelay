/**
 * AI 回答契約サイクル（2026-11-23 改訂）: AI が「人間が判断・行動するために必要な本文」と
 * 「技術的な詳細」を分けて書くための契約を、サーバーがプロンプト先頭に前置する（暫定・
 * 外部 import ゼロの純関数モジュール。`backlog.ts` の `buildBacklogPromptLine` と同じ場所・
 * 同じ作法でプロンプト先頭に差し込む）。
 *
 * 背景（設計の訂正）: 当初「長文を折りたたむ UI」として着手したが、それは意図ではなかった。
 * 振り分けの基準は行数・書式ではなく「それが無いと人間が仕事を進められるか」の一点のみ。
 * 人間が実行する手順・コマンドは、どれだけ長くても省略せず本文に書く契約にする。
 *
 * 分割の実体（境界行の検出・詳細ページへの振り分け）は `response-split-rules.ts`/
 * `response-split.ts` が担う。本モジュールは AI への指示文のみを持つ。
 *
 * 恒久的な配置は Agent 側 Agreement テンプレート（`output-collector.ts`）への統合だが、
 * 3 OS の byte-for-byte 同期・Agreement バージョン更新を伴うため、本サイクルでは
 * ロールアウトの速さを優先してサーバー側の前置のみ実装する（Agent 更新 `u` を待たずに
 * 全マシンへ即時反映できる。Agreement 統合は別サイクルの follow-up）。
 */

import { DETAIL_BOUNDARY_MARKER } from './response-split-rules.js';

/** キルスイッチ（既定 ON）。`'0'` のときだけ無効。`DEVRELAY_BRIEF_REPLY`。 */
export function isBriefReplyEnabled(raw: string | undefined): boolean {
  return raw !== '0';
}

/**
 * サーバーがプロンプト先頭に前置する、AI 回答契約の指示文。
 *
 * 要点:
 * - 振り分け基準は「人間が次に判断・実行するために必要かどうか」の一点のみ（行数や書式ではない）
 * - 人間が実行する手順・コマンドは、どれだけ長くても省略せず本文に書く（詳細側に逃がさない）
 * - 分けなくてよい（詳細が無い）短い回答はそのまま返す（無理に2部構成にしない）
 * - 専門用語を避け、前提知識が無くても読める言葉で書く
 * - 境界行は単独の1行で書く。例として提示する場合はコードブロック内に書く（分割対象は
 *   コードブロック外の境界行のみ）
 */
export const BRIEF_REPLY_PROMPT_LINE = `【回答の書き方】チャットの本文は、人間が次に判断・実行するために必要なことだけを書いてください。結論、判断してほしいこと（選択肢があれば選択肢も）、人間が実行する必要がある手順・コマンド（省略しない。長くても全文を書く）、人間の判断に影響する注意点を書きます。調査した過程・技術的な背景・変更したファイルの内訳・テスト結果の内訳など、人間が読まなくても仕事を進められる情報は、本文の末尾に単独の1行で ${DETAIL_BOUNDARY_MARKER} を書いてから、その続きに書いてください（表示先が自動的に切り分けます。説明のためにこの記法を例示する場合はコードブロックの中に書いてください）。分ける必要がない短い回答は、そのまま返してください（無理に分けなくてよい）。文章は専門用語を避け、前提知識が無くても読める簡潔な言葉にしてください。短くすること自体が目的ではなく、人間が余計な情報を読まずに仕事を進められることが目的です。`;

/**
 * この前置を差し込んでよいターンか判定する。
 * - `terminalMode`（PTY 直打ち）: 書式指示がそのまま端末に打ち込まれてしまうため対象外
 * - `hasStatePolicy`（クロスユーザー ask の隔離/resume ターン）: 既存の前置ロジックと競合させない
 * - `handoverTurn`（引継ぎ書生成）: 書式が厳密に決まっているため対象外
 */
export function shouldPrependBriefReplyLine(input: {
  terminalMode?: boolean;
  hasStatePolicy?: boolean;
  handoverTurn?: boolean;
}): boolean {
  return !input.terminalMode && !input.hasStatePolicy && !input.handoverTurn;
}
